#!/usr/bin/env python3
"""Generate or rotate the LowFarm secrets.

Every value is produced with `secrets.token_urlsafe(32)` — 256 bits of
entropy from the OS CSPRNG.  The script never prints a secret value, only
its SHA-256 prefix, so it is safe to run in a terminal whose output is
shared or logged.

Usage::

    python scripts/generate_secrets.py                  # create if missing
    python scripts/generate_secrets.py --rotate gateway_api_key
    python scripts/generate_secrets.py --rotate all
    python scripts/generate_secrets.py --out /path/to/file

Values are written to ``secrets/lowfarm.env`` with mode 0600.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import secrets
import stat
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUT = REPO_ROOT / "secrets" / "lowfarm.env"
TEMPLATE = REPO_ROOT / "secrets" / "lowfarm.env.example"

# name -> human description, in file order
MANAGED_KEYS: dict[str, str] = {
    "GATEWAY_API_KEY": "Bearer token for the public /v1/* plane",
    "ADMIN_API_KEY": "Bearer token for the /v1/admin/* control plane",
    "WORKER_ADMIN_KEY": "Shared key the workers use to reach the admin plane",
    "GRAFANA_PASSWORD": "Grafana admin password",
}

# Keys that are not secret but belong in the same file.
PASSTHROUGH_KEYS = ["GRAFANA_USER", "WORKER_SEEDS"]

# Values that must never be used in production.
FORBIDDEN = {
    "change-me",
    "changeme",
    "secret",
    "password",
    "admin",
    "lowfarm",
    "test",
    "example",
}


def generate_value() -> str:
    """256 bits of entropy, URL-safe."""
    return secrets.token_urlsafe(32)


def fingerprint(value: str) -> str:
    """Short, non-reversible identifier safe to print."""
    return hashlib.sha256(value.encode("utf-8")).hexdigest()[:12]


def is_weak(value: str) -> bool:
    if len(value) < 24:
        return True
    lowered = value.lower()
    return any(marker in lowered for marker in FORBIDDEN)


def read_existing(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def write_secrets(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# LowFarm secrets — GENERATED by scripts/generate_secrets.py.",
        "# Never commit this file. It is ignored by git.",
        "",
    ]
    for name, description in MANAGED_KEYS.items():
        lines.append(f"# {description}")
        lines.append(f"{name}={values.get(name, '')}")
        lines.append("")
    for name in PASSTHROUGH_KEYS:
        if name in values:
            lines.append(f"{name}={values[name]}")
    # Preserve any other setting the operator added by hand.
    extra = [
        (name, value)
        for name, value in values.items()
        if name not in MANAGED_KEYS and name not in PASSTHROUGH_KEYS and value
    ]
    for name, value in extra:
        lines.append(f"{name}={value}")
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)  # 0600


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", type=Path, default=DEFAULT_OUT, help="output file"
    )
    parser.add_argument(
        "--rotate",
        metavar="KEY",
        default=None,
        help="rotate a single key (or 'all'); default creates only missing keys",
    )
    parser.add_argument(
        "--force", action="store_true", help="rewrite the file from scratch"
    )
    args = parser.parse_args()

    out: Path = args.out
    existing = {} if args.force else read_existing(out)

    if args.rotate == "all":
        targets = list(MANAGED_KEYS)
    elif args.rotate:
        requested = args.rotate.strip().upper()
        if requested not in MANAGED_KEYS:
            print(
                f"unknown key: {args.rotate}\n"
                f"known keys: {', '.join(MANAGED_KEYS)}",
                file=sys.stderr,
            )
            return 2
        targets = [requested]
    else:
        targets = [name for name in MANAGED_KEYS if not existing.get(name)]

    if not targets:
        print(f"all secrets already present in {out} (use --rotate to change them)")
        return 0

    values = dict(existing)
    for name in MANAGED_KEYS:
        values.setdefault(name, "")
    for name in PASSTHROUGH_KEYS:
        values.setdefault(name, "admin")
    values["GRAFANA_USER"] = values.get("GRAFANA_USER") or "admin"

    for name in targets:
        values[name] = generate_value()

    write_secrets(out, values)

    print(f"wrote {out} (mode 0600)")
    for name in targets:
        print(f"  {name:18} sha256:{fingerprint(values[name])}")
    if not out.exists():  # pragma: no cover
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
